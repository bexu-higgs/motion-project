#!/usr/bin/env python3
"""Логотип суретін (ақ фондағы қара) таза векторға айналдырады.

  python3 tools/trace_logo.py path/to/logo.jpg

Әр бөлікті (жұлдыз, VeoSeeBot жазуы, VSE AI ZDES) 8 есе үлкейтіп, шекті мәнмен
бөліп, potrace арқылы қисықтарға айналдырады. Нәтиже:
  assets/logo.js   — intro.html оқитын векторлық жолдар (Path2D)
  assets/logo.svg  — фоны жоқ таза векторлық логотип
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

HERE = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1])
UP = 8          # upscale factor before thresholding -> smooth outlines
PAD = 6         # source px of padding around each part
SMOOTH = 0.55   # edge smoothing, in source px

g = Image.open(SRC).convert("L")
a = np.asarray(g)
inner = np.zeros_like(a, dtype=bool)
inner[30:-30, 30:-30] = True          # the photo has black slivers at its edges — ignore them
dark = (a < 140) & inner

# split into horizontal bands: star / wordmark / tagline
rows = dark.any(1)
bands, start = [], None
for y, v in enumerate(rows):
    if v and start is None:
        start = y
    if not v and start is not None:
        bands.append((start, y)); start = None
assert len(bands) == 3, bands
names = ["star", "word", "tag"]

parts = {}
for name, (y0, y1) in zip(names, bands):
    xs = np.where(dark[y0:y1].any(0))[0]
    x0, x1 = xs.min(), xs.max() + 1
    box = (x0 - PAD, y0 - PAD, x1 + PAD, y1 + PAD)
    crop = g.crop(box)
    big = crop.resize((crop.width * UP, crop.height * UP), Image.LANCZOS)
    big = big.filter(ImageFilter.GaussianBlur(SMOOTH * UP))     # irons out JPEG ripples on the edges
    bw = big.point(lambda v: 0 if v < 128 else 255).convert("1")
    with tempfile.TemporaryDirectory() as td:
        pbm, svg = Path(td) / "in.pbm", Path(td) / "out.svg"
        bw.save(pbm)
        subprocess.run(["potrace", str(pbm), "-s", "-o", str(svg), "-t", "40", "-a", "1.15", "-O", "1.0",
                        "--unit", "1"], check=True)
        text = svg.read_text()
    paths = re.findall(r'<path d="([^"]+)"', text)
    # potrace draws in a y-up space: transform="translate(0,H) scale(1,-1)" with --unit 1
    parts[name] = {
        "box": [int(v) for v in box],          # in source-image px
        "w": crop.width * UP, "h": crop.height * UP,
        "paths": [" ".join(p.split()) for p in paths],
    }
    print(name, "box", box, "paths", len(paths))

out = HERE / "assets"
out.mkdir(exist_ok=True)
(out / "logo.js").write_text("// Generated by tools/trace_logo.py — vector outlines of the VeoSeeBot logo.\n"
                             "window.LOGO = " + json.dumps({"scale": UP, "parts": parts}) + ";\n", encoding="utf-8")

# a clean, background-free SVG of the whole lockup (source-pixel coordinates)
X0 = min(p["box"][0] for p in parts.values()); Y0 = min(p["box"][1] for p in parts.values())
X1 = max(p["box"][2] for p in parts.values()); Y1 = max(p["box"][3] for p in parts.values())
groups = []
for p in parts.values():
    bx, by = p["box"][0] - X0, p["box"][1] - Y0
    groups.append(f'<g transform="translate({bx},{by}) scale({1 / UP}) translate(0,{p["h"]}) scale(1,-1)">'
                  + "".join(f'<path d="{d}"/>' for d in p["paths"]) + "</g>")
(out / "logo.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {X1 - X0} {Y1 - Y0}" fill="currentColor" fill-rule="evenodd">'
    + "".join(groups) + "</svg>\n", encoding="utf-8")
print("wrote", out / "logo.js", out / "logo.svg")
