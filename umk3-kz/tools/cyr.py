def build(rom):
    """returns dict font-> {char: glyph array (16xW)}"""
    out={}
    for font,designs,W in (('small',SMALL,8),('big',BIG,16)):
        S=Shader(rom,font); res={}
        for ch,rows in designs.items():
            m=italic(rows,font,W)
            res[ch]=S.shade(m)
        out[font]=res
    return out
def width_of(g,font):
    cols=np.where((g>=3).any(0))[0]
    if len(cols)==0: return 3
    return int(cols.max())+(1 if font=='small' else 0)
