def calibrate_poles(rig):
    """Find the pole_angle that makes each joint point at its pole target."""
    def err_for(chain_bone, upper, pole_bone, target_bone, test_target, test_pole):
        pbs = rig.pose.bones
        pbs[target_bone].location = test_target
        pbs[pole_bone].location = test_pole
        bpy.context.view_layer.update()
        a = pbs[upper].head.copy()
        j = pbs[chain_bone].head.copy()
        e = pbs[chain_bone].tail.copy()
        p = pbs[pole_bone].head.copy()
        axis = (e - a).normalized()
        jd = (j - a) - axis * (j - a).dot(axis)
        pd = (p - a) - axis * (p - a).dot(axis)
        if jd.length < 1e-6 or pd.length < 1e-6:
            return 0.0
        jd.normalize(); pd.normalize()
        ang = math.atan2(axis.dot(jd.cross(pd)), jd.dot(pd))
        return ang

    for s, sx in (('L', 1), ('R', -1)):
        for chain, upper, pole, tgt, tt, tp in (
                (f'forearm.{s}', f'upperarm.{s}', f'pole_arm.{s}', f'ik_hand.{s}', V(0.05 * sx, -0.25, 0.25), V(0.25 * sx, 0.1, -0.2)),
                (f'shin.{s}', f'thigh.{s}', f'pole_leg.{s}', f'ik_foot.{s}', V(0, -0.1, 0.25), V(0.0, 0.0, 0.0))):
            c = rig.pose.bones[chain].constraints[0]
            c.pole_angle = 0.0
            a0 = err_for(chain, upper, pole, tgt, tt, tp)
            best = None
            for cand in (a0, -a0):
                c.pole_angle = cand
                e = abs(err_for(chain, upper, pole, tgt, tt, tp))
                if best is None or e < best[0]:
                    best = (e, cand)
            c.pole_angle = best[1]
            print(f"pole {chain}: {math.degrees(best[1]):.1f} deg (residual {math.degrees(best[0]):.2f})")
            rig.pose.bones[tgt].location = (0, 0, 0)
            rig.pose.bones[pole].location = (0, 0, 0)
    bpy.context.view_layer.update()


def parent_to_bone(ob, rig, bone):
    ob.parent = rig
    ob.parent_type = 'BONE'
    ob.parent_bone = bone
    b = rig.data.bones[bone]
    ob.matrix_parent_inverse = (b.matrix_local @ Matrix.Translation((0, b.length, 0))).inverted()


