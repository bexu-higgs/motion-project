def flight_root():
    """Root path for the jump: feet follow a parabola while the whole body shrinks."""
    f0, f1 = TT['takeoff'], TT['land']
    o = V(B2_SPOT.x, B2_SPOT.y, 0.0)
    yaw0, yaw1 = math.pi / 2, math.atan2(F_DIR.x, -F_DIR.y)
    if yaw1 - yaw0 > math.pi:
        yaw1 -= 2 * math.pi
    if yaw0 - yaw1 > math.pi:
        yaw1 += 2 * math.pi
    p0 = ROOT_B + Matrix.Rotation(yaw0, 3, 'Z') @ o
    panel = CAN_TABLE + V(0, 0, CAN_PANEL)
    p1 = panel + F_DIR * (0.55 * K_TINY)
    TT['p1'] = p1
    TT['yaw1'] = yaw1
    lnk = math.log(K_TINY)
    for f in range(f0, f1 + 1):
        t = (f - f0) / (f1 - f0)
        u = smooth(t) * 0.35 + t * 0.65
        p = p0.lerp(p1, u)
        p.z = lerp(p0.z, p1.z, u) + 0.4 * 4 * t * (1 - t)
        s = math.exp(lnk * smooth((t - 0.05) / 0.8))
        yaw = lerp(yaw0, yaw1, smooth((t - 0.1) / 0.85))
        root = p - s * (Matrix.Rotation(yaw, 3, 'Z') @ o)
        kroot(f, loc=root, yaw=yaw, scale=s)
    root1 = p1 - K_TINY * (Matrix.Rotation(yaw1, 3, 'Z') @ o)
    kroot(FRAME_END, loc=root1, yaw=yaw1, scale=K_TINY)
    TT['root1'] = root1


