def handheld(ob, amp, period=45.0, seed=0):
    rng = random.Random(seed)
    for i in range(3):
        fc = find_fcurve(ob, 'location', i)
        if fc is None:
            continue
        m = fc.modifiers.new('NOISE')
        m.scale = period
        m.strength = amp * (0.6 if i == 2 else 1.0)
        m.phase = rng.uniform(0, 100)


