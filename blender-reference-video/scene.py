def door_angle(f):
    if f <= 114:
        return 0.0
    if f <= 134:
        return -38.0 * smooth((f - 114) / 20)
    if f <= 152:
        u = (f - 134) / 18
        return lerp(-38.0, -108.0, 1 - (1 - u) ** 2)
    if f <= 160:
        return lerp(-108.0, -104.0, smooth((f - 152) / 8))
    if f <= 358:
        return -104.0
    if f <= 384:
        return lerp(-104.0, 0.0, smooth((f - 358) / 26) ** 1.6)
    if f <= 390:
        return 1.2 * math.sin((f - 384) / 6 * math.pi)
    return 0.0


