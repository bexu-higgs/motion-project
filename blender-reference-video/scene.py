def make_cam(name, lens, fstop=4.0):
    col = collection("Cameras")
    cd = D.cameras.new(name)
    cd.lens = lens
    cd.sensor_width = 36.0
    cd.clip_start = 0.002
    cd.clip_end = 60.0
    cd.dof.use_dof = True
    cd.dof.aperture_fstop = fstop
    cd.dof.aperture_blades = 7
    co = D.objects.new(name, cd)
    col.objects.link(co)
    aim = empty(name + "_aim", (0, 0, 0), col, 0.04)
    foc = empty(name + "_focus", (0, 0, 0), col, 0.03)
    tc = co.constraints.new('TRACK_TO')
    tc.target = aim
    tc.track_axis = 'TRACK_NEGATIVE_Z'
    tc.up_axis = 'UP_Y'
    cd.dof.focus_object = foc
    CAMS[name] = (co, aim, foc)
    return co, aim, foc


