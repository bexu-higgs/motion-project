def surface_y(cx, cz, center, radii, offset=0.0):
    """Front (-Y) surface of an ellipsoid at x,z."""
    q = 1 - ((cx - center.x) / radii[0]) ** 2 - ((cz - center.z) / radii[2]) ** 2
    return center.y - radii[1] * math.sqrt(max(q, 0.0)) - offset


