def mesh_object(name, bm, mat=None, smooth_shade=True, coll=None, mats=None):
    me = D.meshes.new(name)
    bm.normal_update()
    bm.to_mesh(me)
    bm.free()
    if smooth_shade:
        me.shade_smooth()
    ob = D.objects.new(name, me)
    (coll or scene().collection).objects.link(ob)
    for m in (mats or ([mat] if mat else [])):
        me.materials.append(m)
    return ob


def ellipsoid_bm(radii, center=(0, 0, 0), seg=32, rings=16, rot=None, bm=None):
    bm = bm or bmesh.new()
    tmp = bmesh.new()
    bmesh.ops.create_uvsphere(tmp, u_segments=seg, v_segments=rings, radius=1.0)
    c = V(center)
    for v in tmp.verts:
        co = V(v.co.x * radii[0], v.co.y * radii[1], v.co.z * radii[2])
        if rot is not None:
            co = rot @ co
        v.co = co + c
    me = D.meshes.new("_tmp")
    tmp.to_mesh(me)
    tmp.free()
    bm.from_mesh(me)
    D.meshes.remove(me)
    return bm


def capsule_bm(p1, p2, r1, r2, seg=24, cap=7, sx=1.0, sy=1.0, ref=None, bm=None,
               origin=None):
    """Tapered capsule from p1 to p2. Vertices are expressed relative to `origin`."""
    bm = bm or bmesh.new()
    p1, p2 = V(p1), V(p2)
    o = V(origin) if origin is not None else V(0, 0, 0)
    ax = p2 - p1
    L = ax.length
    z = ax.normalized()
    ref = V(ref) if ref is not None else (V(1, 0, 0) if abs(z.x) < 0.9 else V(0, 1, 0))
    x = (ref - z * ref.dot(z)).normalized()
    y = z.cross(x)
    prof = []
    for i in range(1, cap + 1):
        ph = -math.pi / 2 + (math.pi / 2) * i / cap
        prof.append((r1 * math.cos(ph), r1 * math.sin(ph)))
    for i in range(0, cap):
        ph = (math.pi / 2) * i / cap
        prof.append((r2 * math.cos(ph), L + r2 * math.sin(ph)))
    bottom = bm.verts.new(p1 - z * r1 - o)
    top = bm.verts.new(p2 + z * r2 - o)
    rings = []
    for (rr, hz) in prof:
        ring = []
        for j in range(seg):
            a = 2 * math.pi * j / seg
            p = p1 + z * hz + x * (rr * sx * math.cos(a)) + y * (rr * sy * math.sin(a))
            ring.append(bm.verts.new(p - o))
        rings.append(ring)
    for j in range(seg):
        bm.faces.new((bottom, rings[0][(j + 1) % seg], rings[0][j]))
        bm.faces.new((top, rings[-1][j], rings[-1][(j + 1) % seg]))
    for k in range(len(rings) - 1):
        a, b = rings[k], rings[k + 1]
        for j in range(seg):
            bm.faces.new((a[j], a[(j + 1) % seg], b[(j + 1) % seg], b[j]))
    return bm


def lathe_bm(profile, seg=64, bm=None, center=(0, 0, 0)):
    """Revolve [(r, z), ...] (bottom to top) around Z."""
    bm = bm or bmesh.new()
    c = V(center)
    rows = []
    for (r, zz) in profile:
        if r < 1e-7:
            rows.append([bm.verts.new(c + V(0, 0, zz))])
        else:
            rows.append([bm.verts.new(c + V(r * math.cos(2 * math.pi * j / seg),
                                            r * math.sin(2 * math.pi * j / seg), zz))
                         for j in range(seg)])
    for k in range(len(rows) - 1):
        a, b = rows[k], rows[k + 1]
        if len(a) == 1 and len(b) == 1:
            continue
        if len(a) == 1:
            for j in range(seg):
                bm.faces.new((a[0], b[j], b[(j + 1) % seg]))
        elif len(b) == 1:
            for j in range(seg):
                bm.faces.new((a[j], b[0], a[(j + 1) % seg]))
        else:
            for j in range(seg):
                bm.faces.new((a[j], a[(j + 1) % seg], b[(j + 1) % seg], b[j]))
    return bm


def torus_bm(R, r, center=(0, 0, 0), seg=48, mseg=12, sx=1.0, sy=1.0, bm=None, rot=None):
    bm = bm or bmesh.new()
    c = V(center)
    rows = []
    for i in range(seg):
        a = 2 * math.pi * i / seg
        row = []
        for j in range(mseg):
            b = 2 * math.pi * j / mseg
            rr = R + r * math.cos(b)
            p = V(rr * math.cos(a) * sx, rr * math.sin(a) * sy, r * math.sin(b))
            if rot is not None:
                p = rot @ p
            row.append(bm.verts.new(c + p))
        rows.append(row)
    for i in range(seg):
        a, b = rows[i], rows[(i + 1) % seg]
        for j in range(mseg):
            bm.faces.new((a[j], b[j], b[(j + 1) % mseg], a[(j + 1) % mseg]))
    return bm


def rbox(name, size, center, bevel, mat, coll, segs=4, rot_z=0.0):
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co = V(v.co.x * size[0], v.co.y * size[1], v.co.z * size[2])
    ob = mesh_object(name, bm, mat, True, coll)
    ob.location = center
    ob.rotation_euler.z = rot_z
    if bevel > 0:
        md = ob.modifiers.new("Bevel", 'BEVEL')
        md.width = bevel
        md.segments = segs
        md.limit_method = 'NONE'
        md.harden_normals = True
    return ob


def empty(name, loc=(0, 0, 0), coll=None, size=0.1, kind='PLAIN_AXES'):
    e = D.objects.new(name, None)
    e.empty_display_type = kind
    e.empty_display_size = size
    e.location = loc
    (coll or scene().collection).objects.link(e)
    return e


def aim_rotation(loc, target, roll_up='Y'):
    d = (V(target) - V(loc)).normalized()
    return d.to_track_quat('-Z', roll_up).to_euler()


