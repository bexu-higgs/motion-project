def place_hand(side, f, p_rest, target_arm, iters=7, tol=0.0012):
    guess = V(target_arm) - (V(p_rest) - WRI[side])
    for _ in range(iters):
        hand(side, f, guess)
        cur = bone_point(f'hand.{side}', f, p_rest)
        err = V(target_arm) - cur
        if err.length < tol:
            break
        guess = guess + err * 1.0
    return guess


