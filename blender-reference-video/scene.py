def mouth_grid(w, top, bot, curve, shift=0.0):
    """Mouth as a (u, v) grid: u across the width, v from lower to upper lip."""
    pts = []
    for i in range(MOUTH_N + 1):
        u = -1 + 2 * i / MOUTH_N
        k = math.sqrt(max(0.0, 1 - u * u)) ** 0.8
        up = top * k + curve * u * u
        lo = -bot * k + curve * u * u
