#!/usr/bin/env python3
"""Kazakh voiceover with Piper TTS (ISSAI KazakhTTS voice, runs offline).

Each phrase is synthesised separately and placed on the timeline with
narrator-style pauses, which gives exact cue times for the animation.
Writes:
  .cache/build/voice.wav   48 kHz mono voice track (video timeline)
  scene/js/cues.js         window.VO_CUES = {...} start/end of every phrase

Usage: python3 tools/voice.py --model kk-issai-high.onnx [--speaker 3]
Voice download: https://github.com/rhasspy/piper/releases/download/v0.0.2/voice-kk-issai-high.tar.gz
"""
import argparse
import io
import json
import os
import wave

import numpy as np
from piper import PiperVoice, SynthesisConfig

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SR = 48000

# (cue name, text, pause before it in seconds). Numbers are spelled out so
# the narration reads exactly: "2004-ші жылы қыркүйектің 2-сі".
PHRASES = [
    ("men", "Мен —", 0.4),
    ("name", "Оралбекқызы Айназ.", 0.1),
    ("year", "Екі мың төртінші жылы,", 0.3),
    ("month", "қыркүйектің екісі,", 0.06),
    ("oblast", "Алматы облысы,", 0.2),
    ("district", "Кеген ауданы,", 0.14),
    ("village", "Кеген ауылында", 0.2),
    ("born", "өмірге келдім.", 0.04),
]


def synth(voice, text, cfg):
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        voice.synthesize_wav(text, w, syn_config=cfg)
    buf.seek(0)
    with wave.open(buf) as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    # resample to 48 kHz (linear is fine for speech at this ratio)
    t_new = np.arange(int(len(x) * SR / sr)) / SR
    x = np.interp(t_new, np.arange(len(x)) / sr, x).astype(np.float32)
    # trim leading/trailing silence
    env = np.convolve(np.abs(x), np.ones(480) / 480, mode="same")
    idx = np.where(env > 0.012)[0]
    if len(idx):
        x = x[max(0, idx[0] - 240): idx[-1] + 960]
    return x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--speaker", type=int, default=3)  # ISSAI_KazakhTTS_F1_Raya
    ap.add_argument("--length-scale", type=float, default=0.97)
    ap.add_argument("--out", default=os.path.join(ROOT, ".cache", "build", "voice.wav"))
    args = ap.parse_args()

    voice = PiperVoice.load(args.model, config_path=args.model + ".json")
    cfg = SynthesisConfig(speaker_id=args.speaker, length_scale=args.length_scale,
                          noise_scale=0.55, noise_w_scale=0.7)
    t = 0.0
    parts, cues = [], {}
    for name, text, pause in PHRASES:
        x = synth(voice, text, cfg)
        t += pause
        cues[name] = [round(t, 3), round(t + len(x) / SR, 3)]
        parts.append((t, x))
        t += len(x) / SR
    total = t + 0.05
    track = np.zeros(int(total * SR) + 1, dtype=np.float32)
    for start, x in parts:
        i = int(start * SR)
        track[i: i + len(x)] += x
    track *= 0.89 / max(1e-6, np.abs(track).max())

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with wave.open(args.out, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((track * 32767).astype(np.int16).tobytes())
    with open(os.path.join(ROOT, "scene", "js", "cues.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/voice.py - phrase [start, end] in seconds.\n")
        f.write("window.VO_CUES = " + json.dumps(cues, indent=2) + ";\n")
    print(json.dumps(cues), f"total {total:.2f}s")


if __name__ == "__main__":
    main()
